#!/usr/bin/env python3
import sys
from PIL import Image

def main():
    if len(sys.argv) < 4:
        print("usage: convert_image input.png output.inc varname")
        sys.exit(1)

    in_png = sys.argv[1]
    out_inc = sys.argv[2]
    varname = sys.argv[3]

    print(f" CONVERT: {in_png} ({varname})")
    img = Image.open(in_png).convert("RGBA")
    raw_width, raw_height = img.size
    pixels = img.load()

    # detect hotspot
    is_cursor = True
    raw_hot_x, raw_hot_y = 0, 0
    greenpixels = 0

    for i in range(raw_width):
        r, g, b, a = pixels[i, 0]
        if a == 255:
            if g == 255:
                greenpixels += 1
                raw_hot_x = i
            if b != 0 or r != 0:
                is_cursor = False
                break
        elif a != 0:
            is_cursor = False
            break

    if is_cursor and greenpixels == 1:
        greenpixels = 0
        for i in range(raw_height):
            r, g, b, a = pixels[0, i]
            if a == 255:
                if g == 255:
                    greenpixels += 1
                    raw_hot_y = i
                if b != 0 or r != 0:
                    is_cursor = False
                    break
            elif a != 0:
                is_cursor = False
                break
        if greenpixels != 1:
            is_cursor = False
    else:
        is_cursor = False

    if is_cursor:
        width = raw_width - 1
        height = raw_height - 1
        hot_x = raw_hot_x - 1
        hot_y = raw_hot_y - 1
        start_x, start_y = 1, 1
    else:
        width = raw_width
        height = raw_height
        hot_x = 0
        hot_y = 0
        start_x, start_y = 0, 0

    with open(out_inc, "w") as f:
        f.write(f"/* This file is auto-generated from {in_png}\n")
        f.write(" *\n * Do not edit this file directly.\n */\n\n")
        f.write("#include <sys/types.h>\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write("#include <stdbool.h>\n\n")
        f.write("#include <libnsfb.h>\n\n")
        f.write('#include "netsurf/plot_style.h"\n')
        f.write('#include "framebuffer/gui.h"\n')
        f.write('#include "framebuffer/fbtk.h"\n\n')

        f.write(f"static uint8_t {varname}_pixdata[] = {{\n")
        for y in range(start_y, start_y + height):
            f.write("\t")
            for x in range(start_x, start_x + width):
                r, g, b, a = pixels[x, y]
                f.write(f"0x{r:02x}, 0x{g:02x}, 0x{b:02x}, 0x{a:02x}, ")
            f.write("\n")
        f.write("};\n\n")

        f.write(f"struct fbtk_bitmap {varname} = {{\n")
        f.write(f"\t.width\t\t= {width},\n")
        f.write(f"\t.height\t\t= {height},\n")
        f.write(f"\t.hot_x\t\t= {hot_x},\n")
        f.write(f"\t.hot_y\t\t= {hot_y},\n")
        f.write(f"\t.pixdata\t= {varname}_pixdata,\n")
        f.write("};\n\n")

if __name__ == "__main__":
    main()
